#!/bin/bash
# ==============================================================================
# sf-unhook.sh - pre-push フックのアンインストールスクリプト
# ==============================================================================
# sf-hook.sh がインストールした .git/hooks/pre-push を削除する。pre-commit フックは削除しない。
#
# 【使い方】
#   sf-unhook.sh [オプション]
#
# 【オプション】
#   -v, --verbose       : コマンドの応答（出力）をコンソールにも表示する
#   -h, --help          : このヘルプを表示して終了する（1 番目の引数のときだけ）
#   引数の解析はしない。上記以外の引数（2 番目以降の -h / --help を含む）は無視し、削除を実行する。
#
# 【処理の流れ】
#   1. カレントディレクトリに .git ディレクトリがなければ中断する。
#   2. .git/hooks/pre-push がなければ、「すでに無効化されています」と表示して終了する（終了コード 0）。
#   3. .git/hooks/pre-push に目印の文字列（SF_HOOK_MARKER: 「# Generated by sf-tools: wrapper for pre-push hook」）が
#      含まれていなければ、sf-tools が管理するフックではないとして、WARNING を表示し、削除せずに終了する（終了コード 0）。
#   4. 含まれていれば、rm で削除する。
#
# 【前提条件】
#   - force-* ディレクトリで、かつ Git リポジトリのルート（.git ディレクトリがある場所）で実行すること。
#
# 【補足】
#   - .git/hooks/pre-commit（sf-hook.sh がインストールする）は残る。
#   - sf-hook.sh が削除した core.hooksPath（husky の設定）は、元に戻さない。
#   - 終了コード: 成功（削除しなかった場合を含む）は 0。中断・失敗は 1。
#   - ログ: ./sf-tools/logs/sf-unhook.log（実行のたびに作り直す）
# ==============================================================================

# ------------------------------------------------------------------------------
# 1. 共通ライブラリの必須設定
# ------------------------------------------------------------------------------
readonly SCRIPT_NAME=$(basename "$0" .sh)
readonly LOG_FILE="./sf-tools/logs/${SCRIPT_NAME}.log"
readonly LOG_MODE="NEW"


# ------------------------------------------------------------------------------
# 2. 共通ライブラリの読み込み
# ------------------------------------------------------------------------------
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
COMMON_LIB="${SCRIPT_DIR}/../lib/common.sh"

if [[ ! -f "$COMMON_LIB" ]]; then
    echo "[FATAL ERROR] Library not found: $COMMON_LIB" >&2
    exit 1
fi
if [[ "${1:-}" == "--help" || "${1:-}" == "-h" ]]; then
    awk '/^# ==/{f++; next} f==2{sub(/^# ?/,""); print} f==3{exit}' "${BASH_SOURCE[0]}"
    exit 0
fi
source "$COMMON_LIB"
reject_unknown_args "$@"   # -v / --verbose 以外の引数は、不明なオプションとして中断する

# ------------------------------------------------------------------------------
# 3. 定数定義
# ------------------------------------------------------------------------------
# 削除対象: カレントプロジェクトの Git フックファイル
readonly HOOK_DEST=".git/hooks/pre-push"

# SF_HOOK_MARKER は lib/common.sh で定義済み

# ------------------------------------------------------------------------------
# 4. フェーズ定義
# ------------------------------------------------------------------------------

# 【CHECK】実行環境の検証
phase_check_environment() {
    log "INFO" "実行環境を確認中..."

    # Git リポジトリのルートであることを確認
    if [[ ! -d ".git" ]]; then
        die "Gitリポジトリのルートで実行してください（.git ディレクトリが見つかりません）。"
    fi

    return $RET_OK
}

# 【REMOVE】フックファイルの削除
phase_remove_hook() {
    # フックファイルが存在しない場合はすでに無効化済み
    if [[ ! -f "$HOOK_DEST" ]]; then
        log "INFO" "フックはすでに無効化されています（ファイルが存在しません）。"
        return $RET_OK
    fi

    # sf-tools が管理するフックでない場合は誤削除を防ぐためスキップ
    if ! grep -qF "$SF_HOOK_MARKER" "$HOOK_DEST" 2>/dev/null; then
        log "WARNING" "sf-tools が管理するフックではないためスキップしました: $HOOK_DEST"
        return $RET_OK
    fi

    log "INFO" "Git Hook を削除中..."
    run rm "$HOOK_DEST" || return $RET_NG
    log "SUCCESS" "pre-push フックを無効化しました。"

    return $RET_OK
}

# ------------------------------------------------------------------------------
# 5. メイン実行フロー
# ------------------------------------------------------------------------------
log "HEADER" "Git Hook (pre-push) の無効化を開始します (${SCRIPT_NAME}.sh)"

phase_check_environment || die "初期チェックに失敗しました。"
log "SUCCESS" "環境確認完了。"

phase_remove_hook || die "フックの削除に失敗しました。"

echo "--------------------------------------------------------"
log "INFO" "次回以降の git push 時には、自動検証は行われません。"
log "HEADER" "処理が完了しました"

exit $RET_OK
