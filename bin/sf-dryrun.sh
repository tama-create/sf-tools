#!/bin/bash
# ==============================================================================
# sf-dryrun.sh - dry-run 実行スクリプト（sf-release.sh のラッパー）
# ==============================================================================
# sf-release.sh を、このスクリプト自身ではオプションを付け足さずに呼び出す（sf-release.sh の既定が検証モード
# （--dry-run）のため、検証になる）。受け取った引数は、すべてそのまま sf-release.sh へ渡す。
#
# 【使い方】
#   sf-dryrun.sh [オプション]
#
# 【オプション】
#   -n, --no-open       : ブラウザを開かずに実行する
#   -t, --target ALIAS  : 接続先組織のエイリアスを指定する
#   -v, --verbose       : コマンドの応答（出力）をコンソールにも表示する
#   -h, --help          : このヘルプを表示して終了する（1 番目の引数のときだけ。【補足】参照）
#   上記以外も、すべて sf-release.sh へそのまま渡す（-f / -j なども有効。詳細は sf-release.sh --help）。
#
# 【処理の流れ】
#   1. 同じディレクトリの sf-release.sh の存在を確認する。なければ中断する。
#   2. exec bash sf-release.sh "$@" で置き換える（終了コードは sf-release.sh のもの）。
#
# 【前提条件】
#   - force-* ディレクトリ（プロジェクトのルート）で実行すること。その他の前提は sf-release.sh と同じ。
#
# 【補足】
#   - -r / --release を付けると、sf-release.sh がリリースモードになり、実際に組織へリリースする
#     （GitHub Actions 外では、sf-release.sh の確認（Y/N/q）が表示される）。検証だけが目的なら付けないこと。
#   - 2 番目以降の -h / --help は sf-release.sh へ渡り、sf-release.sh のヘルプが表示される
#     （扱いは sf-release.sh --help の【補足】のとおり）。
# ==============================================================================

# ------------------------------------------------------------------------------
# 1. 共通ライブラリの必須設定
# ------------------------------------------------------------------------------
readonly SCRIPT_NAME=$(basename "$0" .sh)
readonly LOG_FILE="./sf-tools/logs/${SCRIPT_NAME}.log"
readonly LOG_MODE="NEW"

# ------------------------------------------------------------------------------
# 2. 共通ライブラリの読み込み
# ------------------------------------------------------------------------------
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
COMMON_LIB="${SCRIPT_DIR}/../lib/common.sh"

if [[ ! -f "$COMMON_LIB" ]]; then
    echo "[FATAL ERROR] Library not found: $COMMON_LIB" >&2
    exit 1
fi
if [[ "${1:-}" == "--help" || "${1:-}" == "-h" ]]; then
    awk '/^# ==/{f++; next} f==2{sub(/^# ?/,""); print} f==3{exit}' "${BASH_SOURCE[0]}"
    exit 0
fi
source "$COMMON_LIB"

# ------------------------------------------------------------------------------
# 3. 初期チェック
# ------------------------------------------------------------------------------
log "HEADER" "dry-run を開始します (${SCRIPT_NAME}.sh)"

RELEASE_SH="${SCRIPT_DIR}/sf-release.sh"
[[ -f "$RELEASE_SH" ]] || die "スクリプトが見つかりません: ${RELEASE_SH}"

# ------------------------------------------------------------------------------
# 4. sf-release.sh を呼び出す（引数はそのまま渡す。-r がなければ、sf-release.sh の既定の検証モード）
# ------------------------------------------------------------------------------
exec bash "$RELEASE_SH" "$@"
